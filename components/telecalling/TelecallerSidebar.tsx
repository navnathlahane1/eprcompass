export default function TelecallerSidebar() {
  const pathname = usePathname();
  const router = useRouter();
  const supabase = getBrowserClient();

  async function handleLogout() {
    await supabase.auth.signOut();
    document.cookie = 'sb-access-token=; Max-Age=0; path=/';
    router.push('/telecalling/login');
  }

  return (
    <aside className="w-56 flex-shrink-0 flex flex-col bg-slate-900/60 border-r border-slate-700/60 h-screen">
      {/* Logo */}
      <div className="px-5 py-5 border-b border-slate-800">
        <div className="flex items-center gap-2">
          <Image src="/imgs/epr-compass/epr-compass-platform.png" alt="EPR Compass" width={36} height={36} className="h-8 w-8 shrink-0 rounded-full object-contain" />
          <span className="font-semibold text-sm text-slate-100">Telecalling</span>
        </div>
      </div>

      {/* Nav */}
      <nav className="flex-1 px-3 py-4 space-y-0.5 overflow-y-auto">
        {NAV_ITEMS.map(({ href, label, icon }) => {
          const active = pathname === href || (href !== '/telecalling/dashboard' && pathname.startsWith(href));
          return (
            <Link
              key={href}
              href={href}
              className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-colors ${
                active
                  ? 'bg-teal-500/10 text-teal-300'
                  : 'text-slate-300 hover:bg-slate-800/40 hover:text-slate-100'
              }`}
            >
              <span className={active ? 'text-teal-400' : 'text-slate-500'}>
                {icon}
              </span>
              {label}
            </Link>
          );
        })}
      </nav>

      {/* Logout */}
      <div className="px-3 py-4 border-t border-slate-800">
        <button
          onClick={handleLogout}
          className="flex items-center gap-3 w-full px-3 py-2.5 rounded-lg text-sm font-medium text-slate-400 hover:bg-slate-800/40 hover:text-slate-300 transition-colors"
        >
          <svg className="w-5 h-5" fill="none" stroke="currentColor" strokeWidth={1.8} viewBox="0 0 24 24">
            <path strokeLinecap="round" strokeLinejoin="round" d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1" />
          </svg>
          Sign out
        </button>
      </div>
    </aside>
  );
}
