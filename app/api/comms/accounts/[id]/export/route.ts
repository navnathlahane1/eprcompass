import { NextRequest, NextResponse } from 'next/server';
import { resolveCommsActor, getCommsAdminClient } from '@/lib/comms/auth';

const ENTITY_LABELS: Record<string, string> = {
  neubrain:          'Neubrain',
  ecovijay_growth:   'EPR Compass',
  eco_vijay_global:  'EPR Compass',
  eco_vijay_events:  'EPR Compass Events',
  eco_vijay_academy: 'EPR Compass Academy',
};

// GET: generate handover pack as Markdown — NO credential values, ever
export async function GET(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  const actor = await resolveCommsActor();
  if (!actor) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });

  const { id } = await params;
  const client = getCommsAdminClient();

  const [accountRes, ownersRes, checklistRes, credFieldsRes] = await Promise.all([
    client.from('comms_accounts').select('*').eq('id', id).eq('is_deleted', false).maybeSingle(),
    client.from('comms_account_owners').select('owner_role, profiles:user_id(full_name, role)').eq('account_id', id),
    client.from('comms_handover_checklist').select('item, is_done, sort_order').eq('account_id', id).order('sort_order'),
    client.from('comms_account_credentials').select('field_name, field_label, created_at').eq('account_id', id).eq('is_deleted', false),
  ]);

  const account   = accountRes.data;
  if (!account) return NextResponse.json({ error: 'Not found' }, { status: 404 });

  const owners    = ownersRes.data ?? [];
  const checklist = checklistRes.data ?? [];
  const credFields = credFieldsRes.data ?? [];

  const exportedAt = new Date().toISOString();
  const primary = owners.find((o: any) => o.owner_role === 'primary');
  const backups  = owners.filter((o: any) => o.owner_role === 'backup');

  const md = [
    `# Handover Pack — ${account.display_name}`,
    ``,
    `> **Generated:** ${exportedAt}  `,
    `> **Exported by:** ${actor.fullName || actor.email}  `,
    `> **⚠️ This document contains NO credential values.** Request access from the primary owner or through the Account Vault.`,
    ``,
    `---`,
    ``,
    `## Account Details`,
    ``,
    `| Field | Value |`,
    `|---|---|`,
    `| Platform | ${account.platform.replace(/_/g, ' ').replace(/\b\w/g, (c: string) => c.toUpperCase())} |`,
    `| Display Name | ${account.display_name} |`,
    account.handle ? `| Handle | @${account.handle.replace(/^@/, '')} |` : null,
    account.profile_url ? `| Profile URL | ${account.profile_url} |` : null,
    account.login_url  ? `| Login URL | ${account.login_url} |` : null,
    `| Account Type | ${account.account_type.replace(/_/g, ' ')} |`,
    `| Brand Entity | ${ENTITY_LABELS[account.brand_entity] ?? account.brand_entity} |`,
    account.region ? `| Region | ${account.region} |` : null,
    `| Status | ${account.status} |`,
    account.tags?.length ? `| Tags | ${account.tags.join(', ')} |` : null,
    ``,
    account.notes ? [`## Notes / SOP`, ``, account.notes, ``] : null,
    `---`,
    ``,
    `## Ownership`,
    ``,
    primary
      ? `**Primary Owner:** ${(primary as any).profiles?.full_name ?? 'Unknown'}  `
      : `**Primary Owner:** Not assigned  `,
    backups.length > 0
      ? `**Backup Owner(s):** ${backups.map((b: any) => b.profiles?.full_name ?? 'Unknown').join(', ')}`
      : `**Backup Owner(s):** None`,
    ``,
    `---`,
    ``,
    `## Stored Credentials`,
    ``,
    `The following credential types are stored in the Account Vault. To retrieve values, a user with \`credentials:reveal\` permission must authenticate via the platform UI.`,
    ``,
    credFields.length > 0
      ? credFields.map((c: any) => `- **${c.field_label || c.field_name.replace(/_/g, ' ')}** *(stored ${new Date(c.created_at).toLocaleDateString()})*`).join('\n')
      : `_No credentials stored yet._`,
    ``,
    `---`,
    ``,
    `## Handover Checklist`,
    ``,
    checklist.length > 0
      ? checklist.map((c: any) => `- [${c.is_done ? 'x' : ' '}] ${c.item}`).join('\n')
      : `_No checklist items._`,
    ``,
    `---`,
    ``,
    `*Generated by EPR Compass Comms Studio — EPR Compass*`,
  ]
    .flat()
    .filter((line): line is string => line !== null)
    .join('\n');

  // Audit
  await client.from('comms_credential_audit').insert({
    account_id:  id,
    actor_id:    actor.id,
    actor_email: actor.email,
    action:      'export',
    metadata:    { exported_at: exportedAt },
    ip_address:  req.headers.get('x-forwarded-for') || null,
  });

  return new NextResponse(md, {
    headers: {
      'content-type':        'text/markdown; charset=utf-8',
      'content-disposition': `attachment; filename="handover-${account.display_name.toLowerCase().replace(/\s+/g, '-')}.md"`,
      'cache-control':       'no-store',
    },
  });
}

