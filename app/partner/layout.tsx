// ─── Layout ───────────────────────────────────────────────────────────────────

export default async function PartnerLayout({ children }: { children: React.ReactNode }) {
  const pathname = (await headers()).get('x-pathname') ?? '';

  if (pathname === '/partner/login' || pathname === '/partner/change-password') {
    return <>{children}</>;
  }

  const authUser = await getAuthenticatedUser();
  if (!authUser || authUser.role !== 'partner') {
    redirect('/partner/login');
  }

  if (authUser.forcePasswordChange) {
    redirect('/partner/change-password');
  }

  return (
    <>
      <PortalShell
        portalName="Partner Portal"
        portalTagline="Channel Partner"
        loginPath="/partner/login"
        storageKey="partner-sidebar-collapsed"
        accent="indigo"
        navSections={NAV_SECTIONS}
        userName={authUser.fullName}
        companyName={authUser.companyName}
        roleLabel="Channel Partner"
        tourSteps={buildPartnerPortalTour(NAV_SECTIONS)}
      >
        {children}
      </PortalShell>
      <IdentifyUser
        userId={authUser.id}
        email={authUser.email}
        role={authUser.role}
        portal="partner"
        companyName={authUser.companyName}
      />
    </>
  );
}
