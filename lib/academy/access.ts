export function canAccessRoute(role: string, pathname: string): boolean {
  const allowed = ACADEMY_ROUTE_ACCESS[role as AcademyRole] ?? [];
  return allowed.some(prefix => pathname === prefix || pathname.startsWith(prefix + '/'));
}
