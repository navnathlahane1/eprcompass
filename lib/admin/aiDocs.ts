export function generateDocsSnapshot() {
  ensureDocsFolders();

  const repoRoot = getRepoRoot();
  const frontendRoot = path.join(repoRoot, 'frontend');
  const backendRoot = path.join(repoRoot, 'backend');
  const supabaseRoot = path.join(repoRoot, 'supabase');

  const frontendApiFiles = listFilesRecursive(path.join(frontendRoot, 'app', 'api'), {
    includeExtensions: ['.ts', '.tsx', '.js', '.jsx'],
  }).map((f) => `frontend/app/api/${f}`);

  const backendApiFiles = [
    ...listFilesRecursive(path.join(backendRoot, 'api'), { includeExtensions: ['.js', '.ts'] }).map((f) => `backend/api/${f}`),
    ...listFilesRecursive(path.join(backendRoot, 'routes'), { includeExtensions: ['.js', '.ts'] }).map((f) => `backend/routes/${f}`),
  ];

  const appRoutes = listFilesRecursive(path.join(frontendRoot, 'app'), {
    includeExtensions: ['.ts', '.tsx', '.js', '.jsx'],
    maxFiles: 7000,
  }).map((f) => `frontend/app/${f}`);

  const migrationFiles = [
    ...listFilesRecursive(path.join(supabaseRoot, 'migrations'), { includeExtensions: ['.sql'] }).map((f) => `supabase/migrations/${f}`),
    ...listFilesRecursive(path.join(backendRoot, 'db', 'migrations'), { includeExtensions: ['.sql'] }).map((f) => `backend/db/migrations/${f}`),
  ];

  const allApiFiles = [...frontendApiFiles, ...backendApiFiles].sort();
  const now = nowIso();
  const version = tryGitCommit();

  writeDoc('architecture/system-overview.md', buildArchitectureDoc(allApiFiles.length, migrationFiles.length, appRoutes.length));
  writeDoc('api/overview.md', buildApiDoc(allApiFiles));
  writeDoc('database/overview.md', buildDatabaseDoc(migrationFiles.sort()));
  writeDoc('workflows/core-workflows.md', buildWorkflowDoc());
  writeDoc('security/access-control.md', buildSecurityDoc());
  writeDoc('integrations/overview.md', buildIntegrationDoc());
  writeDoc('ai-systems/pipeline-overview.md', buildAIDoc());
  writeDoc('sops/regenerate-documentation.md', buildSOPDoc());

  writeDoc(
    'admin-panel/ai-documentation-center.md',
    `# AI Documentation Center\n\nThis module is an internal technical knowledge hub for super admins.\n\n## Features\n\n- Auto-generated documentation\n- Simple explanations for non-technical readers\n- Search across docs\n- Diagram-friendly markdown\n- Print/PDF export\n\n## Last generated\n\n${now}\n`
  );

  writeDoc(
    'change-history/latest.md',
    `# What Changed\n\nGenerated at: ${now}\nCommit: ${version}\n\nThis report summarizes latest architecture and API snapshot updates.\n`
  );

  writeDoc(
    'release-notes/latest.md',
    `# Technical Release Notes\n\nVersion: ${version}\nGenerated: ${now}\n\n## Highlights\n\n- Documentation index refreshed\n- Architecture maps updated\n- API file map refreshed\n- Database migration catalog refreshed\n`
  );

  writeDoc(
    'onboarding/platform-onboarding.md',
    '# Platform Onboarding\n\nStart here to understand the platform in simple language.\n\n1. Read architecture overview\n2. Read API overview\n3. Read database overview\n4. Read core workflows\n'
  );

  writeDoc(
    'deployment/overview.md',
    '# Deployment Overview\n\nDeployment is the process of publishing new code safely.\n\n## Basic flow\n\n1. Developer pushes code\n2. CI checks run\n3. Build is created\n4. App is deployed\n\n\`\`\`mermaid\nflowchart LR\n  Code[Code Push] --> CI[CI Checks]\n  CI --> Build[Build Artifact]\n  Build --> Deploy[Deploy]\n  Deploy --> Monitor[Monitoring]\n\`\`\`\n'
  );

  writeDoc(
    'troubleshooting/common-issues.md',
    '# Troubleshooting\n\n## Docs not updating\n\n- Run generator again\n- Check CI logs\n- Verify docs folder permissions\n\n## Access denied\n\n- Confirm user email is in NEXT_PUBLIC_SUPER_ADMIN_EMAILS\n- Confirm login session is valid\n'
  );

  writeDoc(
    'analytics/overview.md',
    '# Analytics Documentation\n\nAnalytics tells us what is happening in the business and product.\n\nUse dashboards to track trends, exceptions, and performance.\n'
  );

  writeDoc(
    'modules/overview.md',
    '# Module Documentation\n\nEach admin module solves one business area, such as CRM, compliance, billing, and operations.\n'
  );

  const docsRoot = getDocsRoot();
  const mdFiles = listFilesRecursive(docsRoot, { includeExtensions: ['.md'], maxFiles: 10000 });
  const docs: DocIndexItem[] = mdFiles
    .sort()
    .map((rel) => {
      const absolute = path.join(docsRoot, rel);
      const raw = fs.readFileSync(absolute, 'utf8');
      const titleLine = raw.split('\n').find((line) => line.startsWith('# ')) || '# Untitled';
      const title = titleLine.replace(/^#\s+/, '').trim();
      const summary = firstSentence(raw.replace(/^#.*$/m, '').trim()) || 'Auto-generated documentation page.';
      const category = rel.split('/')[0] || 'general';
      const stat = fs.statSync(absolute);
      return {
        path: rel.replace(/\\/g, '/'),
        title,
        category,
        updatedAt: stat.mtime.toISOString(),
        summary,
      };
    });

  const index: DocsIndex = {
    generatedAt: now,
    version,
    repo: tryGitRepo(),
    docs,
  };

  fs.writeFileSync(getIndexPath(), JSON.stringify(index, null, 2), 'utf8');
  return index;
}
