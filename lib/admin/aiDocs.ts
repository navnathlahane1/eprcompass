function cwdRepoRoot(): string {
  const cwd = process.cwd();
  if (path.basename(cwd) === 'frontend') {
    return path.resolve(cwd, '..');
  }
  return cwd;
}

export function getRepoRoot(): string {
  return cwdRepoRoot();
}

export function getDocsRoot(): string {
  // On Vercel/Lambda, process.cwd() is /var/task which is read-only.
  // /tmp is the only writable directory in serverless environments.
  if (process.env.VERCEL || process.cwd().startsWith('/var/task')) {
    return '/tmp/ai-docs';
  }
  return path.join(getRepoRoot(), 'docs');
}

export function getIndexPath(): string {
  return path.join(getDocsRoot(), 'index.json');
}

export async function requireSuperAdmin() {
  const supabase = await createServerComponentClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) {
    return { ok: false as const, status: 401, error: 'Unauthorized' };
  }

  const cookieStore = await import('next/headers').then((m) => m.cookies());
  const isDevBypass =
    process.env.NODE_ENV !== 'production' && cookieStore.get('dev-admin-bypass')?.value === '1';

  if (isDevBypass) {
    return { ok: true as const, user };
  }

  if (!isSuperAdmin(user.email)) {
    return { ok: false as const, status: 403, error: 'Super admin access required' };
  }

  return { ok: true as const, user };
}

export function ensureDocsFolders() {
  const root = getDocsRoot();
  fs.mkdirSync(root, { recursive: true });

  for (const category of DOCS_CATEGORIES) {
    fs.mkdirSync(path.join(root, category), { recursive: true });
  }

  const readmePath = path.join(root, 'README.md');
  if (!fs.existsSync(readmePath)) {
    fs.writeFileSync(
      readmePath,
      '# AI Documentation Center\n\nThis folder is auto-generated by the documentation intelligence system.\n',
      'utf8'
    );
  }
}

function listFilesRecursive(baseDir: string, options?: { includeExtensions?: string[]; maxFiles?: number }) {
  const includeExtensions = options?.includeExtensions || [];
  const maxFiles = options?.maxFiles ?? 5000;
  const out: string[] = [];
  const ignore = new Set([
    'node_modules',
    '.next',
    '.git',
    'dist',
    'build',
    '.vercel',
    'coverage',
    'intel_uploads',
  ]);

  function walk(current: string) {
    if (out.length >= maxFiles) return;
    const entries = fs.readdirSync(current, { withFileTypes: true });
    for (const entry of entries) {
      if (out.length >= maxFiles) return;
      const fullPath = path.join(current, entry.name);
      const relPath = path.relative(baseDir, fullPath).replace(/\\/g, '/');

      if (entry.isDirectory()) {
        if (ignore.has(entry.name)) continue;
        walk(fullPath);
      } else {
        if (includeExtensions.length > 0) {
          const ext = path.extname(entry.name).toLowerCase();
          if (!includeExtensions.includes(ext)) continue;
        }
        out.push(relPath);
      }
    }
  }

  if (fs.existsSync(baseDir)) walk(baseDir);
  return out;
}

function firstSentence(input: string): string {
  const normalized = String(input || '').replace(/\s+/g, ' ').trim();
  if (!normalized) return '';
  const match = normalized.match(/^(.{1,180}?[.!?])\s/);
  if (match?.[1]) return match[1];
  return normalized.slice(0, 180);
}

export function readIndex(): DocsIndex {
  const indexPath = getIndexPath();
  if (!fs.existsSync(indexPath)) {
    return { generatedAt: '', version: '0.0.0', repo: '', docs: [] };
  }

  const raw = fs.readFileSync(indexPath, 'utf8');
  return JSON.parse(raw) as DocsIndex;
}

export function safeDocPath(rawPath: string): string | null {
  const docsRoot = getDocsRoot();
  const normalized = String(rawPath || '').replace(/\\/g, '/').replace(/^\/+/, '');
  const target = path.resolve(docsRoot, normalized);
  if (!target.startsWith(docsRoot)) return null;
  if (!fs.existsSync(target)) return null;
  if (!target.endsWith('.md')) return null;
  return target;
}

function tryGitCommit(): string {
  try {
    return execSync('git rev-parse --short HEAD', {
      cwd: getRepoRoot(),
      stdio: ['ignore', 'pipe', 'ignore'],
      encoding: 'utf8',
    }).trim();
  } catch {
    return 'unknown';
  }
}

function tryGitRepo(): string {
  try {
    const url = execSync('git config --get remote.origin.url', {
      cwd: getRepoRoot(),
      stdio: ['ignore', 'pipe', 'ignore'],
      encoding: 'utf8',
    }).trim();
    return url || 'local-repo';
  } catch {
    return 'local-repo';
  }
}

function writeDoc(relativePath: string, content: string) {
  const fullPath = path.join(getDocsRoot(), relativePath);
  fs.mkdirSync(path.dirname(fullPath), { recursive: true });
  fs.writeFileSync(fullPath, content, 'utf8');
}

function nowIso() {
  return new Date().toISOString();
}

